import { ico, moonSvg } from './icons.js';

/**
 * The loading screen, as markup. It is written into index.html (so it shows before any script has loaded) by
 * scripts/inject-loader.mjs, and test/client/loader-markup.test.js fails if the page and this ever drift apart.
 * The moon is built pixel by pixel as the game loads; five shards fly in to it.
 */
export function loaderHtml() {
  const shards = [0, 1, 2, 3, 4].map((i) => `<span class="ld-shard" data-i="${i}">${ico('shard', 18)}</span>`).join('');
  return `<div id="ms-loader" class="ms-loader" role="progressbar" aria-label="Loading"><div class="ld-stage"><div class="ld-moon" id="ldMoon">${moonSvg(true)}</div>${shards}</div><div class="ld-logo">MOONSHARD</div><div class="ld-bar"><i id="ldFill"></i></div><div class="ld-cap"><span>Loading the forest</span><b id="ldPct">0%</b></div></div>`;
}

export const LOADER_START = '<!-- loader:start (generated by scripts/inject-loader.mjs from src/ui/loaderMarkup.js) -->';
export const LOADER_END = '<!-- loader:end -->';
